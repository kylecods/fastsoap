using System.Collections.Generic;
using System.Text;
using FastSoap.Generators.Models;
using Microsoft.CodeAnalysis.CSharp;

namespace FastSoap.Generators.Emission
{

    /// <summary>
    /// Emits deterministic, reflection-free C# source files for validated <see cref="ServiceGenerationModel"/> contracts.
    /// </summary>
    internal static class SoapContractEmitter
    {

        #region Internal Methods

        /// <summary>
        /// Generates the static <c>&lt;ServiceName&gt;SoapContract</c> descriptor class source.
        /// </summary>
        /// <param name="model">The validated service generation model.</param>
        /// <returns>Deterministic C# source text using LF line endings.</returns>
        internal static string EmitContractClass(ServiceGenerationModel model)
        {
            StringBuilder sb = new StringBuilder(1024);
            string accessibility = model.IsPublic ? "public" : "internal";
            string contractClassName = $"{model.ServiceName}SoapContract";
            bool hasNamespace = !string.IsNullOrWhiteSpace(model.TargetNamespace);
            string indent = hasNamespace ? "    " : string.Empty;

            sb.Append("// <auto-generated />\n");
            sb.Append("#nullable enable\n\n");

            if (hasNamespace)
            {
                sb.Append("namespace ").Append(model.TargetNamespace).Append('\n');
                sb.Append("{\n\n");
            }

            sb.Append(indent).Append("/// <summary>\n");
            sb.Append(indent).Append("/// Generated SOAP operation descriptors for <see cref=\"").Append(model.ServiceFullyQualifiedName).Append("\"/>.\n");
            sb.Append(indent).Append("/// </summary>\n");
            sb.Append(indent).Append(accessibility).Append(" static class ").Append(contractClassName).Append('\n');
            sb.Append(indent).Append("{\n\n");

            sb.Append(indent).Append("    #region Fields\n\n");
            sb.Append(indent).Append("    /// <summary>\n");
            sb.Append(indent).Append("    /// Gets the logical SOAP service contract name.\n");
            sb.Append(indent).Append("    /// </summary>\n");
            sb.Append(indent).Append("    public const string ServiceName = ").Append(FormatStringLiteral(model.ServiceName)).Append(";\n\n");
            sb.Append(indent).Append("    /// <summary>\n");
            sb.Append(indent).Append("    /// Gets the XML target namespace URI for the service contract.\n");
            sb.Append(indent).Append("    /// </summary>\n");
            sb.Append(indent).Append("    public const string ServiceNamespace = ").Append(FormatStringLiteral(model.ServiceNamespace)).Append(";\n\n");
            sb.Append(indent).Append("    #endregion\n\n");

            if (!model.Operations.IsEmpty)
            {
                sb.Append(indent).Append("    #region Properties\n\n");

                foreach (OperationGenerationModel op in model.Operations)
                {
                    sb.Append(indent).Append("    /// <summary>\n");
                    sb.Append(indent).Append("    /// Gets the immutable descriptor for the <c>").Append(op.OperationName).Append("</c> SOAP operation.\n");
                    sb.Append(indent).Append("    /// </summary>\n");
                    sb.Append(indent).Append("    public static global::FastSoap.Abstractions.SoapOperationDescriptor ").Append(op.OperationName).Append(" { get; } =\n");
                    sb.Append(indent).Append("        new global::FastSoap.Abstractions.SoapOperationDescriptor(\n");
                    sb.Append(indent).Append("            ").Append(FormatStringLiteral(op.OperationName)).Append(",\n");
                    sb.Append(indent).Append("            ").Append(FormatStringLiteral(op.Action)).Append(",\n");
                    sb.Append(indent).Append("            ").Append(op.ReplyAction is null ? "null" : FormatStringLiteral(op.ReplyAction)).Append(",\n");
                    sb.Append(indent).Append("            new global::FastSoap.Abstractions.SoapQName(").Append(FormatStringLiteral(op.RequestNamespace)).Append(", ").Append(FormatStringLiteral(op.RequestLocalName)).Append("),\n");
                    sb.Append(indent).Append("            new global::FastSoap.Abstractions.SoapQName(").Append(FormatStringLiteral(op.ResponseNamespace)).Append(", ").Append(FormatStringLiteral(op.ResponseLocalName)).Append("));\n\n");
                }

                sb.Append(indent).Append("    #endregion\n\n");
            }

            sb.Append(indent).Append("}\n");

            if (hasNamespace)
            {
                sb.Append("\n}\n");
            }

            return sb.ToString();
        }

        /// <summary>
        /// Generates the static <c>Map&lt;ServiceName&gt;</c> typed registration helper class source.
        /// </summary>
        /// <param name="model">The validated service generation model.</param>
        /// <returns>Deterministic C# source text using LF line endings.</returns>
        internal static string EmitRegistrationExtensions(ServiceGenerationModel model)
        {
            StringBuilder sb = new StringBuilder(2048);
            string accessibility = model.IsPublic ? "public" : "internal";
            string extensionClassName = $"{model.ServiceName}SoapEndpointRouteBuilderExtensions";
            string contractFqn = string.IsNullOrWhiteSpace(model.TargetNamespace)
                ? $"global::{model.ServiceName}SoapContract"
                : $"global::{model.TargetNamespace}.{model.ServiceName}SoapContract";

            List<string> distinctContexts = new List<string>();
            Dictionary<string, string> contextFieldNames = new Dictionary<string, string>(System.StringComparer.Ordinal);
            foreach (OperationGenerationModel op in model.Operations)
            {
                RegisterContextField(op.RequestContextFullyQualifiedName, distinctContexts, contextFieldNames);
                RegisterContextField(op.ResponseContextFullyQualifiedName, distinctContexts, contextFieldNames);
            }

            sb.Append("// <auto-generated />\n");
            sb.Append("#nullable enable\n\n");
            sb.Append("using global::FastSoap.AspNetCore;\n\n");
            sb.Append("namespace Microsoft.AspNetCore.Builder\n");
            sb.Append("{\n\n");
            sb.Append("    /// <summary>\n");
            sb.Append("    /// Generated ASP.NET Core SOAP endpoint registration helpers for <see cref=\"").Append(model.ServiceFullyQualifiedName).Append("\"/>.\n");
            sb.Append("    /// </summary>\n");
            sb.Append("    ").Append(accessibility).Append(" static class ").Append(extensionClassName).Append('\n');
            sb.Append("    {\n\n");

            if (distinctContexts.Count > 0)
            {
                sb.Append("        #region Fields\n\n");

                foreach (string contextFqn in distinctContexts)
                {
                    string fieldName = contextFieldNames[contextFqn];
                    sb.Append("        private static readonly ").Append(contextFqn).Append(' ').Append(fieldName).Append(" = new ").Append(contextFqn).Append("(\n");
                    sb.Append("            new global::CloudNimble.Text.Xml.XmlSerializerOptions\n");
                    sb.Append("            {\n");
                    sb.Append("                AllowDuplicateProperties = false,\n");
                    sb.Append("                OmitXmlDeclaration = true,\n");
                    sb.Append("                UnmappedMemberHandling = global::CloudNimble.Text.Xml.Serialization.XmlUnmappedMemberHandling.Disallow\n");
                    sb.Append("            });\n\n");
                }

                sb.Append("        #endregion\n\n");
            }

            sb.Append("        #region Public Methods\n\n");
            sb.Append("        /// <summary>\n");
            sb.Append("        /// Maps all declared SOAP operations for <see cref=\"").Append(model.ServiceFullyQualifiedName).Append("\"/> at <paramref name=\"pattern\"/>.\n");
            sb.Append("        /// </summary>\n");
            sb.Append("        /// <param name=\"endpoints\">The ASP.NET Core endpoint route builder.</param>\n");
            sb.Append("        /// <param name=\"pattern\">The route pattern for the SOAP endpoint.</param>\n");
            sb.Append("        /// <returns>An <see cref=\"global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder\"/> for further endpoint configuration.</returns>\n");
            sb.Append("        ").Append(accessibility).Append(" static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder ").Append(model.RegistrationMethodName).Append("(\n");
            sb.Append("            this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints,\n");
            sb.Append("            string pattern)\n");
            sb.Append("        {\n");
            sb.Append("            return ").Append(model.RegistrationMethodName).Append("(endpoints, pattern, configure: null);\n");
            sb.Append("        }\n\n");
            sb.Append("        /// <summary>\n");
            sb.Append("        /// Maps all declared SOAP operations for <see cref=\"").Append(model.ServiceFullyQualifiedName).Append("\"/> at <paramref name=\"pattern\"/> with optional endpoint customization.\n");
            sb.Append("        /// </summary>\n");
            sb.Append("        /// <param name=\"endpoints\">The ASP.NET Core endpoint route builder.</param>\n");
            sb.Append("        /// <param name=\"pattern\">The route pattern for the SOAP endpoint.</param>\n");
            sb.Append("        /// <param name=\"configure\">An optional callback to customize the <see cref=\"global::FastSoap.AspNetCore.SoapEndpointBuilder\"/> (options, header handlers, or metadata).</param>\n");
            sb.Append("        /// <returns>An <see cref=\"global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder\"/> for further endpoint configuration.</returns>\n");
            sb.Append("        ").Append(accessibility).Append(" static global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder ").Append(model.RegistrationMethodName).Append("(\n");
            sb.Append("            this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints,\n");
            sb.Append("            string pattern,\n");
            sb.Append("            global::System.Action<global::FastSoap.AspNetCore.SoapEndpointBuilder>? configure = null)\n");
            sb.Append("        {\n");
            sb.Append("            global::System.ArgumentNullException.ThrowIfNull(endpoints);\n");
            sb.Append("            global::System.ArgumentException.ThrowIfNullOrWhiteSpace(pattern);\n\n");
            sb.Append("            return endpoints.MapSoap(\n");
            sb.Append("                pattern,\n");
            sb.Append("                soap =>\n");
            sb.Append("                {\n");

            foreach (OperationGenerationModel op in model.Operations)
            {
                string requestArg = op.RequestMemberName is null ? "wire" : $"wire.{op.RequestMemberName}";
                string ctArg = op.HasCancellationToken ? ", ct" : string.Empty;
                string requestContextField = contextFieldNames[op.RequestContextFullyQualifiedName];
                string responseContextField = contextFieldNames[op.ResponseContextFullyQualifiedName];

                sb.Append("                    soap.MapOperation<").Append(op.RequestWireFullyQualifiedName).Append(", ").Append(op.ResponseWireFullyQualifiedName).Append(">(\n");
                sb.Append("                        descriptor: ").Append(contractFqn).Append('.').Append(op.OperationName).Append(",\n");
                sb.Append("                        requestType: ").Append(requestContextField).Append('.').Append(op.RequestContextPropertyName).Append(",\n");
                sb.Append("                        responseType: ").Append(responseContextField).Append('.').Append(op.ResponseContextPropertyName).Append(",\n");
                sb.Append("                        handler: static async (wire, context, ct) =>\n");
                sb.Append("                        {\n");
                sb.Append("                            ").Append(model.ServiceFullyQualifiedName).Append(" service = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<").Append(model.ServiceFullyQualifiedName).Append(">(context.Services);\n");

                if (op.ResponseMemberName is null)
                {
                    sb.Append("                            return await service.").Append(op.MethodName).Append('(').Append(requestArg).Append(ctArg).Append(").ConfigureAwait(false);\n");
                }
                else
                {
                    sb.Append("                            ").Append(op.ServiceReturnInnerFullyQualifiedName).Append(" result = await service.").Append(op.MethodName).Append('(').Append(requestArg).Append(ctArg).Append(").ConfigureAwait(false);\n");
                    sb.Append("                            return new ").Append(op.ResponseWireFullyQualifiedName).Append('\n');
                    sb.Append("                            {\n");
                    sb.Append("                                ").Append(op.ResponseMemberName).Append(" = result\n");
                    sb.Append("                            };\n");
                }

                sb.Append("                        });\n");
            }

            sb.Append("                    configure?.Invoke(soap);\n");
            sb.Append("                });\n");
            sb.Append("        }\n\n");
            sb.Append("        #endregion\n\n");
            sb.Append("    }\n\n");
            sb.Append("}\n");

            return sb.ToString();
        }

        #endregion

        #region Private Methods

        private static string FormatStringLiteral(string value)
        {
            return SymbolDisplay.FormatLiteral(value, quote: true);
        }

        private static void RegisterContextField(
            string contextFqn,
            List<string> distinctContexts,
            Dictionary<string, string> contextFieldNames)
        {
            if (contextFieldNames.ContainsKey(contextFqn))
            {
                return;
            }

            string fieldName = distinctContexts.Count == 0
                ? "s_context"
                : $"s_context{distinctContexts.Count + 1}";

            distinctContexts.Add(contextFqn);
            contextFieldNames.Add(contextFqn, fieldName);
        }

        #endregion

    }

}
